import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createWorker} from 'tesseract.js';
import {OnPagePdfEditor} from '../src/on-page-editor.js';
const e=await OnPagePdfEditor.create();
const original=new Uint8Array(fs.readFileSync('test-output/outlined-fixture.pdf'));
let view=e.open(original);assert.equal(view.kind,'outlined');assert.equal(view.objects.length,0);
e.renderOcr();
const worker=await createWorker('eng',1,{langPath:path.resolve('public/ocr'),cacheMethod:'none'});
const {data}=await worker.recognize(path.resolve('test-output/outlined-fixture.png'),{},{blocks:true});
await worker.terminate();
const lines=(data.blocks||[]).flatMap(b=>b.paragraphs||[]).flatMap(p=>p.lines||[]).filter(l=>l.text.trim()).map(l=>({text:l.text.trim(),confidence:l.confidence,rect:{x:l.bbox.x0/3,y:l.bbox.y0/3,w:(l.bbox.x1-l.bbox.x0)/3,h:(l.bbox.y1-l.bbox.y0)/3}}));
view=e.setOcrLines(lines);assert(view.objects.length>=4);
console.log('Recognized synthetic lines:',view.objects.map(o=>({font:o.fontName,size:o.size})));
const target=view.objects.find(o=>o.text.startsWith('Click'));
assert(target);
const spec=e.inline(target.index);assert(spec.image.data.length);assert(spec.fontData?.length);
console.log('On-page font data:',spec.fontData.length,'bytes.');
view=await e.apply(target.index,'Edit this text and type directly.');
assert(view.objects.some(o=>o.text==='Edit this text and type directly.'));
assert.equal(view.objects.length,4,'Converted text must not appear twice.');
fs.writeFileSync('test-output/outlined-edited.pdf',e.download());
const saved=e.download();
view=await e.apply(target.index,'Edit this text directly.');
assert(view.objects.some(o=>o.text==='Edit this text directly.'));
e.undo();assert.deepEqual(e.download(),saved);
e.undo();assert.deepEqual(e.download(),original);
e.open(saved);e.renderOcr();view=e.setOcrLines(lines);
assert.equal(view.objects.length,4,'Reopened mixed PDFs must retain all editable lines.');
assert.equal(view.objects.filter(o=>o.mode==='exact').length,1);
assert.equal(view.objects.filter(o=>o.mode==='approximate').length,3);
console.log('PASS: outlined OCR selection, local font matching, direct editing data, vector removal, export, surrounding pixel preservation, repeated editing, undo and reopening mixed text/outline PDFs.');
