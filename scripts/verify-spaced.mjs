import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createWorker} from 'tesseract.js';
import {OnPagePdfEditor} from '../src/on-page-editor.js';
const e=await OnPagePdfEditor.create();
const original=new Uint8Array(fs.readFileSync('test-output/spaced-outlines.pdf'));
e.open(original);e.renderOcr();
const worker=await createWorker('eng',1,{langPath:path.resolve('public/ocr'),cacheMethod:'none'});
await worker.setParameters({preserve_interword_spaces:'1',user_defined_dpi:'216'});
const {data}=await worker.recognize(path.resolve('test-output/spaced-outlines.png'),{},{blocks:true});await worker.terminate();
const rect=b=>({x:b.x0/3,y:b.y0/3,w:(b.x1-b.x0)/3,h:(b.y1-b.y0)/3});
const lines=(data.blocks||[]).flatMap(b=>b.paragraphs||[]).flatMap(p=>p.lines||[]).map(l=>({text:l.text.trim(),confidence:l.confidence,rect:rect(l.bbox),words:(l.words||[]).map(w=>({text:w.text,confidence:w.confidence,rect:rect(w.bbox)}))}));
let v=e.setOcrLines(lines);
assert(v.objects.some(o=>o.text==='Name:'));assert(v.objects.some(o=>o.text==='Alex Example'));
const value=v.objects.find(o=>o.text==='Alex Example'),label=v.objects.find(o=>o.text==='Name:');
const labelBox={...label.box};e.inline(value.index);v=await e.apply(value.index,'Alex Sample');
assert.deepEqual(v.objects.find(o=>o.text==='Name:').box,labelBox);
const reference=v.objects.find(o=>o.text==='12345');e.inline(reference.index);v=await e.apply(reference.index,'54321');
assert(v.objects.some(o=>o.text==='Alex Sample'));assert(v.objects.some(o=>o.text==='54321'));
fs.writeFileSync('test-output/spaced-outlines-edited.pdf',e.download());
const bytes=e.download();await assert.rejects(e.apply(value.index,'X'.repeat(500)),/overlaps|beyond/);assert.deepEqual(e.download(),bytes);
assert(e.view().objects.length>=6);
e.open(new Uint8Array(fs.readFileSync('test-output/spaced-native.pdf')));v=e.view();
assert.equal(v.objects.length,4);assert(v.objects.every(o=>String(o.index).startsWith('range:')));
const nativeValue=v.objects.find(o=>o.text==='Alex Example'),nativeReference=v.objects.find(o=>o.text==='12345'),oldBox={...nativeReference.box};
assert(e.inline(nativeValue.index).image.data.length);
v=await e.apply(nativeValue.index,'Alex Sample');assert.deepEqual(v.objects.find(o=>o.text==='12345').box,oldBox);
const nativeLabel=v.objects.find(o=>o.text==='Reference:');v=await e.apply(nativeLabel.index,'Reference!');
assert(v.objects.some(o=>o.text==='54321')===false);assert.deepEqual(v.objects.find(o=>o.text==='12345').box,oldBox);
fs.writeFileSync('test-output/spaced-native-edited.pdf',e.download());
const beforeFailure=e.download(),save=e.e.save.bind(e.e);e.e.save=()=>new Uint8Array(fs.readFileSync('test-output/spaced-native.pdf'));
await assert.rejects(e.apply(v.objects.find(o=>o.text==='Alex Sample').index,'Alex Saved'),/preserve|cancelled/);
e.e.save=save;assert.deepEqual(e.download(),beforeFailure);assert.equal(e.view().objects.length,4);
e.open(original);assert.equal(e.view().kind,'outlined');
console.log('PASS: separated labels/values, page transform export, multiple edits, exact native font/size, fixed sibling positions, rollback after export failure, and opening a new PDF after failure.');
