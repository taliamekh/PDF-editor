import fs from 'node:fs';
import assert from 'node:assert/strict';
import { ExactPdfEditor } from '../src/pdf-editor.js';

const editor = await ExactPdfEditor.create();
const bytes = new Uint8Array(fs.readFileSync(new URL('../test-output/fixture.pdf',import.meta.url)));
let view = editor.open(bytes);
const sample = view.objects.find(o=>o.text.startsWith('Original'));
assert(sample);
console.log('Editing',sample.fontName,sample.size);
view = await editor.apply(sample.index, 'Original edited text 12345.');
assert(view.objects.some(o=>o.text === 'Original edited text 12345.' && o.size===13.5));
fs.writeFileSync(new URL('../test-output/edited.pdf',import.meta.url),editor.download());
const bg = view.objects.find(o=>o.text.startsWith('Text on'));
view = await editor.apply(bg.index,'Text on a coloured background!');
assert(view.objects.find(o=>o.index===bg.index).size===14);
const rotated = view.objects.find(o=>o.text.startsWith('Rotated'));
view = await editor.apply(rotated.index,'Rotated text edited.');
assert(view.objects.find(o=>o.index===rotated.index).size>11.99);
const standard = view.objects.find(o=>o.text.startsWith('Standard'));
view = await editor.apply(standard.index,'Standard text edited.');
assert(view.objects.find(o=>o.index===standard.index).fontName==='Helvetica');
const saved = editor.download();
await assert.rejects(editor.apply(sample.index,'An unsupported character Ω.'),/original embedded font/);
assert.deepEqual(editor.download(),saved);
await assert.rejects(editor.apply(sample.index,'Long '.repeat(300)),/extends beyond|overlaps/);
assert.deepEqual(editor.download(),saved);
await assert.rejects(editor.apply(sample.index,'New\nline'),/no line breaks/);
view = editor.view(1);
assert.equal(view.objects[0].text,'Second page text stays unchanged.');
editor.undo();
assert.equal(editor.edits,3);
fs.writeFileSync(new URL('../test-output/all-edits.pdf',import.meta.url),editor.download());
editor.view(0);
const remove = editor.view().objects.find(o=>o.text.startsWith('Standard'));
const deletion = await editor.apply(remove.index,'');
assert(!deletion.objects.some(o=>o.text.startsWith('Standard')));
editor.undo();
assert(editor.view().objects.some(o=>o.text.startsWith('Standard')));
assert.throws(()=>editor.open(new Uint8Array([1,2,3])),/could not be opened/);
assert(editor.view().objects.some(o=>o.text.startsWith('Original edited')));
const rotatedFile = new URL('../test-output/rotated-page.pdf',import.meta.url);
if(fs.existsSync(rotatedFile)) {
  let rotatedView = editor.open(new Uint8Array(fs.readFileSync(rotatedFile)));
  const target = rotatedView.objects.find(o=>o.text.startsWith('Original'));
  assert(target.box.x>=0 && target.box.y>=0);
  rotatedView = await editor.apply(target.index,'Original edited text 12345.');
  assert(rotatedView.objects.some(o=>o.text==='Original edited text 12345.'));
  fs.writeFileSync(new URL('../test-output/rotated-page-edited.pdf',import.meta.url),editor.download());
}
console.log('PASS: embedded font and exact size; background and rotated text; standard font; missing-glyph, overflow and multiline rejection; rollback; second page; undo.');
